"""
Generate desktop/assets/icon.png (speech bubble with a face outline). Run with the project venv.

This was generated by Claude for better visibility
"""
from pathlib import Path
from PIL import Image, ImageDraw

S = 4096
img = Image.new("RGBA", (S, S), (0, 0, 0, 0))
d = ImageDraw.Draw(img)
k = S / 1024
def r(*v): return [x * k for x in v]
# macOS-style rounded square background with vertical gradient
bg = Image.new("RGBA", (S, S))
bd = ImageDraw.Draw(bg)
for y in range(S):
    t = y / S
    bd.line([(0, y), (S, y)], fill=(int(30 + 20 * t), int(40 + 30 * t), int(80 + 70 * t), 255))
mask = Image.new("L", (S, S), 0)
ImageDraw.Draw(mask).rounded_rectangle(r(40, 40, 984, 984), radius=210 * k, fill=255)
img.paste(bg, (0, 0), mask)
# speech bubble
d.rounded_rectangle(r(170, 220, 854, 700), radius=150 * k, fill=(245, 247, 252, 255))
d.polygon(r(300, 680, 300, 850, 480, 690), fill=(245, 247, 252, 255))
# face outline inside bubble
ink = (40, 55, 110, 255)
d.ellipse(r(392, 270, 632, 560), outline=ink, width=int(24 * k))
for cx in (462, 562):
    d.ellipse(r(cx - 16, 380, cx + 16, 412), fill=ink)
d.arc(r(452, 440, 572, 520), 20, 160, fill=ink, width=int(20 * k))
# sound waves right of the bubble
for i, rad in enumerate((70, 120)):
    d.arc(r(700 - rad, 460 - rad, 700 + rad, 460 + rad), -50, 50, fill=(110, 168, 255, 255), width=int(22 * k))
out = Path(__file__).resolve().parents[1] / "assets" / "icon.png"
img.resize((1024, 1024), Image.LANCZOS).save(out)
print(out)
